import { Module } from '@nestjs/common';
import { APP_GUARD } from '@nestjs/core';
import { ConfigModule, ConfigService } from '@nestjs/config';
import { LoggerModule } from 'nestjs-pino';
import { ThrottlerModule, ThrottlerGuard } from '@nestjs/throttler';
import { ClsModule } from 'nestjs-cls';
import { DatabaseModule } from '@core/database/database.module';
import { LedgerResolverModule } from '@core/accounting/ledger-resolver.module';
import { ErrorsModule } from '@core/errors/errors.module';
import { UserModule } from './modules/user/user.module';
import { AuthModule } from './modules/auth/auth.module';
import { v4 as uuidv4 } from 'uuid';
import { SocietyModule } from './modules/society/society.module';
import { FlatModule } from './modules/flat/flat.module';
import { MemberModule } from './modules/member/member.module';
import { MaintenanceModule } from './modules/maintenance/maintenance.module';
import { PaymentModule } from './modules/payment/payment.module';
import { AccountingModule } from './modules/accounting/accounting.module';
import { ResidentModule } from './modules/resident/resident.module';
import { ComplaintModule } from './modules/complaint/complaint.module';
import { AssetModule } from './modules/asset/asset.module';
import { ReportModule } from './modules/report/report.module';
import { NotificationModule } from './modules/notification/notification.module';
import { SuperAdminModule } from './modules/superadmin/superadmin.module';
import { AIModule } from './modules/ai/ai.module';
import { HealthModule } from './modules/health/health.module';
import { QueueModule } from './modules/queue/queue.module';
import { WorkerModule } from './modules/worker/worker.module';
import { AuditModule } from './core/audit/audit.module';
import { StaffModule } from './modules/staff/staff.module';
import { FacilityModule } from './modules/facility/facility.module';
import { CommitteeModule } from './modules/committee/committee.module';
import { MeetingModule } from './modules/meeting/meeting.module';
import { VisitorModule } from './modules/visitor/visitor.module';
import { FundModule } from './modules/fund/fund.module';
import { DirectoryModule } from './modules/directory/directory.module';
import { ChatModule } from './modules/chat/chat.module';
import { CustomReportModule } from './modules/custom-report/custom-report.module';
import { SearchModule } from './modules/search/search.module';
import { StorageModule } from './core/storage/storage.module';

@Module({
  imports: [
    ConfigModule.forRoot({
      isGlobal: true,
      envFilePath: ['.env.local', '.env'],
    }),
    LoggerModule.forRoot({
      pinoHttp: {
        genReqId: (req: any) => req.id, // Use the ID generated by ClsModule
        transport: process.env.NODE_ENV !== 'production'
          ? { target: 'pino-pretty', options: { colorize: true, singleLine: true } }
          : undefined,
        autoLogging: false,
      },
    }),
    ThrottlerModule.forRoot([{
      ttl: 60000,
      limit: 120, // 120 requests per minute per IP
    }]),
    ClsModule.forRoot({
      global: true,
      middleware: {
        mount: true,
        generateId: true,
        idGenerator: (req: any) => req.headers['x-request-id'] || uuidv4(),
        setup: (cls, req: any) => {
          // The society is set only by TenantGuard after it verifies membership. Never trust the raw x-tenant-id
          // header here: routes without that guard would otherwise run against any society the caller names.
          cls.set('tenantId', null);
        },
      },
    }),
    DatabaseModule,
    LedgerResolverModule,
    ErrorsModule,
    UserModule,
    AuthModule,
    SocietyModule,
    FlatModule,
    MemberModule,
    MaintenanceModule,
    PaymentModule,
    AccountingModule,
    ResidentModule,
    ComplaintModule,
    StaffModule,
    FacilityModule,
    CommitteeModule,
    MeetingModule,
    VisitorModule,
    FundModule,
    DirectoryModule,
    ChatModule,
    AssetModule,
    ReportModule,
    NotificationModule,
    SuperAdminModule,
    AIModule,
    HealthModule,
    QueueModule,
    WorkerModule,
    AuditModule,
    CustomReportModule,
    SearchModule,
    StorageModule,
  ],
  controllers: [],
  providers: [
    {
      provide: APP_GUARD,
      useClass: ThrottlerGuard,
    },
  ],
})
export class AppModule {}
